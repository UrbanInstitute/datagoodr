#' Demo dataset for the datagoodr vignettes
#'
#' A small synthetic dataset with one column per data type, so each vignette can
#' build a real DGF and render a real profile for every reporting style. Values
#' are deliberately in their messy "as-entered" form (dates as `M/D/YYYY`, a
#' boolean as `yes`/`no`, a zero-padded FIPS code) so the typing and
#' stabilization steps have something to do.
#'
#' @format A data frame with 60 rows and 6 variables:
#' \describe{
#'   \item{event_date}{character; a calendar date written `M/D/YYYY` (temporal).}
#'   \item{region}{character; one of four regions (categorical).}
#'   \item{is_active}{character; `"yes"`/`"no"`, recoded to logical (boolean).}
#'   \item{revenue}{numeric; a right-skewed dollar amount (number).}
#'   \item{county_fips}{character; a zero-padded 5-digit county FIPS (identifier).}
#'   \item{notes}{character; short free-text notes (text).}
#' }
#' @source Generated by `data-raw/dg_demo.R`.
"dg_demo"


#' Baseball players: a messy test dataset
#'
#' Career records for the 678 major league players whose first appearance
#' (debut) fell in 2010-2014. Every column is text exactly as it arrived -
#' written and ISO dates, dollar-formatted salaries, `R`/`L`/`B` codes, and
#' non-US birthplaces in `birthState` - so typing and stabilizing have real
#' work to do. Pair it with [dg_baseball_dictionary] for labels and
#' descriptions; `vignette("example-guides")` builds a research guide from it.
#'
#' @format A data frame with 678 rows and 19 character variables:
#' \describe{
#'   \item{nameFirst, nameLast}{player's first and last name.}
#'   \item{birthDate}{date of birth, written `Mon DD, YYYY`.}
#'   \item{birthYear, birthMonth}{year and month (`Mon`) of birth.}
#'   \item{birthState, birthCity}{place of birth: a US state code or a region
#'     name elsewhere, and a city.}
#'   \item{weight, height}{weight in pounds and height in inches.}
#'   \item{bats, throws}{batting side (`R`/`L`/`B`) and throwing hand (`R`/`L`).}
#'   \item{debut, finalGame}{dates of first and last appearance, `YYYY-MM-DD`.}
#'   \item{G, AB, H}{career games, at bats and hits.}
#'   \item{AVG, SLUG}{career batting average and slugging percentage; blank
#'     with no recorded at bats.}
#'   \item{salary}{salary, written `$851,950`.}
#' }
#' @source A subset of the baseball test file `data-dev/bb.csv` in the
#'   datagoodr source repository; built by `data-raw/dg_baseball.R`.
#' @seealso [dg_baseball_dictionary]
"dg_baseball"


#' Data dictionary for the baseball test dataset
#'
#' One row per column of [dg_baseball]: a short label and a description, ready
#' for the `dd_vlabel` and `dd_vdesc` arguments of [create_dgf()].
#'
#' @format A data frame with 19 rows and 3 character variables:
#' \describe{
#'   \item{variable}{column name in [dg_baseball], in the same order.}
#'   \item{label}{short plain-language label, e.g. `"batting average"`.}
#'   \item{description}{one-sentence description.}
#' }
#' @source Built by `data-raw/dg_baseball.R` from
#'   `data-dev/bb-data-dictionary.csv`.
#' @seealso [dg_baseball]
"dg_baseball_dictionary"


#' US states: a merged test dataset
#'
#' The 50 US states built by merging base R's `state.x77` indicators with a
#' hand-entered table of state mottos on the state name. It mixes every data
#' type datagoodr renders - character, factor, logical, numeric and a
#' temporal/year column - and keeps real missing values (Alaska has no English
#' translation; Washington's unofficial motto has no adoption year), so typing,
#' stabilization and the missingness summaries all have something to do.
#'
#' @format A data frame with 50 rows and 16 variables:
#' \describe{
#'   \item{state}{state name (character, identifier).}
#'   \item{region}{Census region (factor): `Northeast`, `South`,
#'     `North Central`, `West`.}
#'   \item{south, west}{logical flags for the South and West regions.}
#'   \item{population}{population estimate, July 1 1975 (thousands).}
#'   \item{income}{per-capita income, 1974 (dollars).}
#'   \item{illiteracy}{illiteracy, 1970 (percent of population).}
#'   \item{life_exp}{life expectancy, 1969-71 (years).}
#'   \item{murder}{murder and non-negligent manslaughter rate per 100,000, 1976.}
#'   \item{hs_grad}{high-school graduates, 1970 (percent of population).}
#'   \item{frost}{mean number of days per year with minimum temperature below
#'     freezing, 1931-1960, in the capital or a large city.}
#'   \item{area}{land area (square miles).}
#'   \item{motto}{state motto, in its original language.}
#'   \item{motto_english}{English translation; `NA` when the motto is already
#'     English or no translation was recorded.}
#'   \item{motto_year}{year the motto was adopted; `NA` for Washington's
#'     unofficial motto.}
#'   \item{id}{a hash of the state name (character, identifier).}
#' }
#' @source The numeric indicators, region and flags come from `state.x77`,
#'   `state.region` and `state.name` in the base R \pkg{datasets} package; the
#'   mottos, translations and years are hand-entered. Built by
#'   `data-raw/dg_states.R`.
"dg_states"
