#' Demo dataset for the datagoodr vignettes
#'
#' A small synthetic dataset with one column per data type, so each vignette can
#' build a real DGF and render a real profile for every reporting style. Values
#' are deliberately in their messy "as-entered" form (dates as `M/D/YYYY`, a
#' boolean as `yes`/`no`, a zero-padded FIPS code) so the typing and
#' stabilization steps have something to do.
#'
#' @format A data frame with 60 rows and 6 variables:
#' \describe{
#'   \item{event_date}{character; a calendar date written `M/D/YYYY` (temporal).}
#'   \item{region}{character; one of four regions (categorical).}
#'   \item{is_active}{character; `"yes"`/`"no"`, recoded to logical (boolean).}
#'   \item{revenue}{numeric; a right-skewed dollar amount (number).}
#'   \item{county_fips}{character; a zero-padded 5-digit county FIPS (identifier).}
#'   \item{notes}{character; short free-text notes (text).}
#' }
#' @source Generated by `data-raw/dg_demo.R`.
"dg_demo"


#' Baseball players: a messy test dataset
#'
#' Career records for the 678 major league players whose first appearance
#' (debut) fell in 2010-2014. Every column is text exactly as it arrived -
#' written and ISO dates, dollar-formatted salaries, `R`/`L`/`B` codes, and
#' non-US birthplaces in `birthState` - so typing and stabilizing have real
#' work to do. Pair it with [dg_baseball_dictionary] for labels and
#' descriptions; `vignette("example-guides")` builds a research guide from it.
#'
#' @format A data frame with 678 rows and 19 character variables:
#' \describe{
#'   \item{nameFirst, nameLast}{player's first and last name.}
#'   \item{birthDate}{date of birth, written `Mon DD, YYYY`.}
#'   \item{birthYear, birthMonth}{year and month (`Mon`) of birth.}
#'   \item{birthState, birthCity}{place of birth: a US state code or a region
#'     name elsewhere, and a city.}
#'   \item{weight, height}{weight in pounds and height in inches.}
#'   \item{bats, throws}{batting side (`R`/`L`/`B`) and throwing hand (`R`/`L`).}
#'   \item{debut, finalGame}{dates of first and last appearance, `YYYY-MM-DD`.}
#'   \item{G, AB, H}{career games, at bats and hits.}
#'   \item{AVG, SLUG}{career batting average and slugging percentage; blank
#'     with no recorded at bats.}
#'   \item{salary}{salary, written `$851,950`.}
#' }
#' @source A subset of the baseball test file `data-dev/bb.csv` in the
#'   datagoodr source repository; built by `data-raw/dg_baseball.R`.
#' @seealso [dg_baseball_dictionary]
"dg_baseball"


